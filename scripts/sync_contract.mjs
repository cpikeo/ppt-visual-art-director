#!/usr/bin/env node
/* 把 scripts/limits.json 里的图表契约（chart.contract + deemphasis + defaults.palette）生成为 web/contract.js，
   chart.js 只读它。`--check` 只比对不写（CI 用）：不同步即退出 1。 */
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.join(HERE, '..');
const L = JSON.parse(fs.readFileSync(path.join(HERE, 'limits.json'), 'utf8'));
const c = { ...L.chart.contract }; delete c._readme;
const body = { dark_luminance: L.contrast.dark_background_luminance, contract: c, deemphasis: L.chart.deemphasis, palette: L.defaults.palette.map((x) => x.toUpperCase()), style: L.chart.style };
const src = `/* GENERATED by scripts/sync_contract.mjs from scripts/limits.json — do not edit. */\nwindow.DK_CONTRACT = ${JSON.stringify(body, null, 1)};\n`;
const dest = path.join(ROOT, 'web', 'contract.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  if (cur !== src) { console.error('web/contract.js 与 scripts/limits.json 不同步：运行 node scripts/sync_contract.mjs'); process.exit(1); }
  console.log('contract in sync'); 
} else { fs.writeFileSync(dest, src); console.log('wrote', path.relative(ROOT, dest)); }
